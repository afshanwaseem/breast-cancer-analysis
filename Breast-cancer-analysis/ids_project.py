# Step 1: Load and Clean the Data
def load_and_clean_data(file_path):
    # Specify the encoding when reading the CSV file
    data = pd.read_csv('data.csv', encoding='latin-1')  # or 'ISO-8859-1'
    # Drop columns with all null values
    data = data.dropna(axis=1, how='all')
    # Keep columns with at least 50% non-null values
    data = data.loc[:, data.isnull().mean() < 0.5]
    # Rename columns for consistency
    data.columns = data.columns.str.strip().str.lower().str.replace(' ', '_').str.replace(r'[^\w]', '', regex=True)
    # Fill missing values in categorical columns with 'Unknown'
    for col in data.select_dtypes(include=['object']).columns:
        data[col] = data[col].fillna('Unknown')
    # Fill missing values in numerical columns with median
    for col in data.select_dtypes(include=['float64', 'int64']).columns:
        data[col] = data[col].fillna(data[col].median())
    return data

