def side_effect_graph(data):
    # List of columns that represent side effects
    side_effect_columns = ['headache', 'dizziness', 'fainting', 'weekness', 'fatigue']

    # Convert to binary (1 for any occurrence, 0 for no occurrence)
    side_effect_data = data[side_effect_columns].applymap(lambda x: 1 if x > 0 else 0)

    # Calculate the percentage of patients experiencing each side effect
    side_effect_percentages = side_effect_data.mean() * 100

    # Create a bar plot
    plt.figure(figsize=(10, 6))
    ax = sns.barplot(x=side_effect_percentages.index, y=side_effect_percentages.values, palette='viridis')

    # Add the percentage values on top of the bars
    for i, v in enumerate(side_effect_percentages.values):
        ax.text(i, v + 2, f'{v:.1f}%', ha='center', va='bottom', fontsize=10, color='black')  # Adjust the position and font

    plt.xticks(rotation=90)
    plt.title('Percentage of Patients Experiencing Chemotherapy Side Effects')
    plt.xlabel('Side Effect')
    plt.ylabel('Percentage (%)')
    plt.tight_layout()
    plt.show()

